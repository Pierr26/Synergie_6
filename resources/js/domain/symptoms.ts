import type { Role, WorkspaceId } from './types';

/**
 * "Report a symptom": the capture (report + attachment) is kept apart from the medical review.
 * Report and attachment IDs are stable UUIDs, so a later analysis step can attach a suggestion to
 * a report and submit it to the CMO for validation. No automated analysis exists in this lot.
 */
export type SymptomStatus = 'draft' | 'submitted' | 'reviewed';

export interface SymptomReport {
    id: string;
    ws: WorkspaceId;
    missionId: string;
    crewId: string;
    status: SymptomStatus;
    description: string;
    bodyArea: string;
    /** when the sign was first noticed (ISO, UTC) */
    noticedAt: string;
    attachmentId: string | null;
    createdAt: string;
    /** last local write: the "Saved on this device" time */
    savedAt: string;
    submittedAt: string | null;
    reviewedAt: string | null;
}

export interface SymptomAttachment {
    id: string;
    ws: WorkspaceId;
    crewId: string;
    reportId: string;
    name: string;
    mime: string;
    size: number;
    /** image bytes, kept in IndexedDB only: never in /public, the service worker cache or a ground report */
    data: ArrayBuffer;
    /** true for the fictional image generated by the demo */
    simulated: boolean;
    createdAt: string;
}

/** One entry of the human review thread. `reply` is the crew member answering a request for more information. */
export type ReviewKind = 'note' | 'more-info' | 'completed' | 'reply';

export interface SymptomReviewEntry {
    id: string;
    ws: WorkspaceId;
    reportId: string;
    crewId: string;
    kind: ReviewKind;
    authorId: string;
    authorRole: Role;
    text: string;
    at: string;
    /** position in the thread: the demo clock can stand still, so time alone does not order entries */
    seq: number;
}

export const BODY_AREAS = ['Head', 'Face', 'Eyes', 'Mouth', 'Neck', 'Chest', 'Abdomen', 'Back', 'Left arm', 'Right arm', 'Left hand', 'Right hand', 'Left leg', 'Right leg', 'Left foot', 'Right foot', 'Skin, several areas', 'Other'] as const;

export const PHOTO_TYPES = ['image/jpeg', 'image/png', 'image/webp'] as const;
export const PHOTO_MAX_BYTES = 5 * 1024 * 1024;

/** Returns an error message the crew member can act on, or null when the file is accepted. */
export function validatePhoto(file: { type: string; size: number }): string | null {
    if (!(PHOTO_TYPES as readonly string[]).includes(file.type)) return 'This file is not a JPEG, PNG or WebP image. Choose a photo in one of these formats; your text is kept.';
    if (file.size === 0) return 'This file is empty. Take the photo again or choose another one; your text is kept.';
    if (file.size > PHOTO_MAX_BYTES) return `This photo is ${(file.size / 1024 / 1024).toFixed(1)} MB. The limit is 5 MB: take it again at a lower resolution or choose another one; your text is kept.`;
    return null;
}

export interface SymptomInput {
    description: string;
    bodyArea: string;
    noticedAt: string;
}

/** Field errors that block a submission (a draft can be saved incomplete). */
export function validateSubmission(input: SymptomInput, now: number): Partial<Record<keyof SymptomInput, string>> {
    const errors: Partial<Record<keyof SymptomInput, string>> = {};
    if (input.description.trim().length < 3) errors.description = 'Describe what you see in a few words.';
    if (!(BODY_AREAS as readonly string[]).includes(input.bodyArea)) errors.bodyArea = 'Choose the body area.';
    const t = Date.parse(input.noticedAt);
    if (Number.isNaN(t)) errors.noticedAt = 'Enter the mission day and time you noticed it.';
    else if (t > now + 60_000) errors.noticedAt = 'This time is in the future. Enter when you noticed it.';
    return errors;
}

/** Whether the CMO is waiting for an answer from the crew member. */
export function awaitingReply(thread: SymptomReviewEntry[]): boolean {
    const last = [...thread].sort((a, b) => a.seq - b.seq).filter((e) => e.kind === 'more-info' || e.kind === 'reply').pop();
    return last?.kind === 'more-info';
}

